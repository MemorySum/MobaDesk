<#
.SYNOPSIS
    Builds a ClickOnce deployment for MobaDesk.

.DESCRIPTION
    Uses src\MobaDesk\Properties\PublishProfiles\ClickOnceProfile.pubxml.

    WinUI 3 / Windows App SDK self-contained apps need the Windows App SDK reg-free WinRT
    manifest embedded in the apphost, but MSBuild switches to an external manifest as soon as
    ClickOnce manifests are enabled. Visual Studio avoids that conflict by building first and
    then running PublishOnly; this script does the same in two MSBuild invocations.

    It uses the .NET Framework MSBuild that ships with Visual Studio, because the ClickOnce
    bootstrapper (setup.exe) is generated by GenerateBootstrapper, which the .NET Core MSBuild
    does not support (MSB4803).

    Output: publish\clickonce\setup.exe, MobaDesk.application and Application Files\.

.EXAMPLE
    .\build-clickonce.ps1

.EXAMPLE
    .\build-clickonce.ps1 -Configuration Debug
#>
[CmdletBinding()]
param(
    [string]$Configuration = 'Release',
    [string]$Platform = 'x64'
)

$ErrorActionPreference = 'Stop'

$repoRoot = $PSScriptRoot
$project = Join-Path $repoRoot 'src\MobaDesk\MobaDesk.csproj'
$profileName = 'ClickOnceProfile'
$outputDir = Join-Path $repoRoot 'publish\clickonce'

if (-not (Test-Path $project)) {
    throw "Cannot find project '$project' (script root: '$repoRoot')."
}

function Find-VsMSBuild {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (Test-Path $vswhere) {
        $paths = & $vswhere -latest -products * -requires Microsoft.Component.MSBuild `
            -find 'MSBuild\**\Bin\MSBuild.exe' 2>$null
        if ($paths) { return ($paths | Select-Object -First 1) }
    }

    $onPath = Get-Command MSBuild.exe -ErrorAction SilentlyContinue
    if ($onPath) { return $onPath.Source }

    return $null
}

$msbuild = Find-VsMSBuild
if (-not $msbuild) {
    Write-Host 'Visual Studio MSBuild (MSBuild.exe) was not found.' -ForegroundColor Yellow
    Write-Host 'ClickOnce needs the .NET Framework MSBuild that ships with Visual Studio:'
    Write-Host '  https://visualstudio.microsoft.com/'
    Write-Host 'The .NET SDK alone is not enough (dotnet msbuild cannot run GenerateBootstrapper).'
    exit 1
}
Write-Host "MSBuild: $msbuild" -ForegroundColor DarkGray

# ClickOnce ApplicationVersion must have four numeric parts.
[xml]$projectXml = Get-Content $project -Encoding UTF8
$version = ($projectXml.Project.PropertyGroup.Version | Where-Object { $_ } | Select-Object -First 1)
if (-not $version) { $version = '1.0.0' }
$parts = @($version -split '\.')
while ($parts.Count -lt 4) { $parts += '0' }
$clickOnceVersion = ($parts[0..3] -join '.')

$commonArgs = @(
    $project,
    "/p:Configuration=$Configuration",
    "/p:Platform=$Platform",
    "/p:SelfContained=true",
    "/p:RuntimeIdentifier=win-x64",
    "/p:MobaDeskSlimPayload=false",
    "/p:ApplicationVersion=$clickOnceVersion",
    '/nologo',
    '/v:minimal'
)

# Step 1: a normal build. This embeds the Windows App SDK merged manifest into the apphost.
Write-Host ''
Write-Host "Step 1/2: build ($Configuration|$Platform)..." -ForegroundColor Cyan
& $msbuild @commonArgs '/t:Rebuild'
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$targetDir = Get-ChildItem (Join-Path $repoRoot "src\MobaDesk\bin\$Platform\$Configuration") -Recurse -Filter 'MobaDesk.exe' -ErrorAction SilentlyContinue |
    Where-Object { $_.FullName -match '\\win-x64\\' -and $_.FullName -notmatch '\\publish\\' } |
    Select-Object -First 1
if (-not $targetDir) {
    throw "Could not find the built MobaDesk.exe under src\MobaDesk\bin\$Platform\$Configuration."
}
$embeddedSize = $targetDir.Length
if ($embeddedSize -lt 200KB) {
    throw "Built apphost is only $embeddedSize bytes; the Windows App SDK manifest was not embedded. Do not pass GenerateManifests/GenerateClickOnceManifests to the build step."
}

# Step 2: produce the ClickOnce deployment from the already-built apphost.
Write-Host "Step 2/2: publish ClickOnce ($profileName)..." -ForegroundColor Cyan
& $msbuild @commonArgs '/t:PublishOnly' "/p:PublishProfile=$profileName"
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

$appFolder = Join-Path $outputDir ("Application Files\MobaDesk_" + ($clickOnceVersion -replace '\.', '_'))
$setup = Join-Path $outputDir 'setup.exe'
$manifest = Join-Path $outputDir 'MobaDesk.application'
$appExe = Join-Path $appFolder 'MobaDesk.exe'
$pri = Join-Path $appFolder 'MobaDesk.pri'

foreach ($required in @($setup, $manifest, $appExe, $pri)) {
    if (-not (Test-Path $required)) { throw "ClickOnce output is incomplete, missing '$required'." }
}

$setupInfo = Get-Item $setup
$hash = (Get-FileHash -Algorithm SHA256 -Path $setup).Hash
$stat = Get-ChildItem $outputDir -Recurse -File | Measure-Object -Property Length -Sum

Write-Host ''
Write-Host 'ClickOnce deployment ready:' -ForegroundColor Green
Write-Host "  $setup"
Write-Host ("  size:   {0:N1} MB (setup.exe)" -f ($setupInfo.Length / 1MB))
Write-Host ("  folder: {0:N1} MB / {1} files" -f ($stat.Sum / 1MB), $stat.Count)
Write-Host "  version: $clickOnceVersion"
Write-Host "  sha256:  $hash"
Write-Host ''
Write-Host 'Run setup.exe to install per-user; it creates the Start menu/desktop shortcut and an uninstall entry.'
